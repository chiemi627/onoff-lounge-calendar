// ============================================================
// 設定ファイル（ここだけ触れば運用調整できます）
// ============================================================

// 取得するICSのURL。GitHub Actions では Secrets の ICS_URL を使うので
// ここは空のままでOK（ローカル実行時は環境変数 ICS_URL を指定）。
export const ICS_URL = process.env.ICS_URL || '';

// 出力先
export const OUT_DIR = 'docs/data';

// ------------------------------------------------------------
// 期間の窓（軽量化の要）
//   過去は PAST_DAYS 日分だけ残し、それ以前は捨てる。
//   未来は FUTURE_DAYS 日先まで。
// ------------------------------------------------------------
export const PAST_DAYS = 31;
export const FUTURE_DAYS = 400;

// ------------------------------------------------------------
// 個人名の伏せ字ルール
//   Jicoo予約は SUMMARY が「〈氏名〉 OnOffラウンジ予約」形式になる。
//   → 既定ではこれを丸ごと MASKED_LABEL に置き換える。
//   ただし KEEP_IF_INCLUDES の語を含むものは「公開イベント」とみなして残す
//   （例:「最終講義（担当: 安） OnOffラウンジ予約」→「最終講義（担当: 安）」）。
// ------------------------------------------------------------
export const MASKED_LABEL = '予約済み';

// この正規表現にマッチしたら個人予約とみなす
export const BOOKING_SUFFIX = /[\s　]*OnOff[\s　]*ラウンジ予約[\s　]*$/;

// ↑にマッチしても、これらの語を含むならイベント名として残す
export const KEEP_IF_INCLUDES = [
  '講義', '授業', '見学', '説明会', '交流', '委員会', 'オープンキャンパス',
  'ワークショップ', 'イベント', 'カレッジ',
];

// 上のルールに関係なく必ず伏せたいタイトル（正規表現の配列）
// 個人名だけのタイトルなどはここに追加してください。
export const ALWAYS_MASK = [
  /^中村大地$/,
];

// タイトル末尾に付く担当者名を落としたいときはここにパターンを足す
// 例: /\s*打ち合わせ\s*渡辺$/ → '打ち合わせ'
export const TRIM_PATTERNS = [
  [/[\s　]*打ち合わせ[\s　]*渡辺[\s　]*$/, ' 打ち合わせ'],
];

// LOCATION をページに出すか。「対面」しか入っていないなら false でよい。
export const SHOW_LOCATION = false;

// DESCRIPTION は個人情報（メッセージ本文）を含み、かつ容量の大半を占めるので
// 常に破棄する。出したくなった場合でも要再検討。

// ------------------------------------------------------------
// 同じ日・同じタイトルの予定が細切れに並んでいる場合
// （例: 学園祭の予約が1コマずつ7件）、この分数以内の隙間なら
// 1ブロックに結合する。0 で無効。
// ------------------------------------------------------------
export const MERGE_GAP_MIN = 15;

// ------------------------------------------------------------
// 貸切表示
//   このカレンダーに予定が入っている＝ラウンジが貸切、という前提で
//   すべての予定に EXCLUSIVE_LABEL を付ける。
//   「誰でも立ち寄れる公開イベント」があれば OPEN_PATTERNS に足すと
//   別扱い（OPEN_LABEL）になる。
// ------------------------------------------------------------
export const EXCLUSIVE_LABEL = '貸切';
export const OPEN_LABEL = '公開';
export const OPEN_PATTERNS = [
  // 例: /手話サロン/, /手話カフェ/, /入学式/
];

// ラウンジの通常開放時間（月グリッドの帯の目盛りに使う。分単位）
export const OPEN_FROM_MIN = 8 * 60 + 30;
export const OPEN_TO_MIN = 20 * 60;
